/// <summary>
/// FIX-83: registers an earlier release generated stay valid across an upgrade whose generator output changes. The upgrade rewrites a
/// member only when its bytes are exactly an earlier implementation's rendition of the same sources; a hand edit is never overwritten.
/// </summary>
[Collection("upgrade")]
public sealed class GeneratedMemberUpgradeTests
{
    private const string Target = "0.9.0";
    private const string NotRecorded = "Not recorded in this revision. Absence supplies no inferred value or permission.";

    // The registers 0.8.4 wrote with an earlier implementation, and the record fields the current implementation added after it.
    private static readonly (string Generator, string Directory, string Type, string Earlier, (string Field, string Label)[] Added)[] Registers =
    [
        ("vericairn.records/work-orders", "work", "work-order", "vericairn.records/work-orders/1", [("disclosure", "Disclosure")]),
        ("vericairn.records/releases", "releases", "release", "vericairn.records/releases/1",
            [("line", "Line"), ("channel", "Channel"), ("endOfSupport", "End Of Support"), ("backportOf", "Backport Of")]),
    ];

    [Fact]
    public void AnUpgradeRewritesTheMembersAnEarlierGeneratorWroteAndTheEstateCheckThenPasses()
    {
        using var f = new PolicyFixture();
        using EstateService service = Prepare(f);
        IReadOnlyList<Member> members = Members(service.Session.Load());
        Assert.Equal(4, members.Count);
        foreach (Member member in members) File.WriteAllBytes(Full(f, member.Path), member.Earlier);

        // What 0.9.0 reports for an estate whose registers 0.8.4 wrote, before this fix: every member edited, and new sources refused.
        EstateModel opened = service.Session.Load();
        Assert.Equal(members.Select(m => "Generated bytes differ: " + m.Path).Order(StringComparer.Ordinal),
            EstateChecks.Run(opened).Where(x => x.Code == "document.generated-edited").Select(x => x.Message).Order(StringComparer.Ordinal));
        WriteOutcome refused = service.NewRecord(new("work-order", f.Estate.OperatorId, PolicyFixture.Element(WorkOrder("TASK-LATER"))));
        Assert.False(refused.Ok);
        Assert.True(refused.Problem!.Message.Contains("Repair the existing generated members", StringComparison.Ordinal), JsonSerializer.Serialize(refused.Problem));

        Dictionary<string, byte[]> before = Snapshot(f.Estate.Root);
        (UpgradeResponse? preview, Problem? previewProblem) = service.Upgrade(new UpgradeRequest(Target, null, true));
        Assert.Null(previewProblem);
        Assert.False(preview!.Applied);
        Assert.Equal(members.Select(m => m.Path).Order(StringComparer.Ordinal), preview.Regenerated);
        AssertSnapshot(before, Snapshot(f.Estate.Root));

        (UpgradeResponse? applied, Problem? problem) = service.Upgrade(new UpgradeRequest(Target, f.Estate.OperatorId, false));
        Assert.True(problem is null, JsonSerializer.Serialize(problem));
        Assert.True(applied!.Applied);
        Assert.Equal(preview.Regenerated, applied.Regenerated);
        EstateModel moved = service.Session.Load();
        Assert.Equal(Target, moved.Manifest!.Version);
        Assert.False(moved.Findings.HasErrors, string.Join('\n', moved.Findings));
        FindingList checks = EstateChecks.Run(moved);
        Assert.DoesNotContain(checks, x => x.Severity == Severity.Error);
        Assert.DoesNotContain(checks, x => x.Code.StartsWith("document.", StringComparison.Ordinal));
        foreach (Member member in members) Assert.Equal(member.Current, File.ReadAllBytes(Full(f, member.Path)));

        // Only the rewritten members, the manifest and the migration record changed.
        RecordEnvelope migration = Assert.Single(moved.OfType("migration"));
        Assert.Equal(migration.Id, applied.Migration!.Id);
        Dictionary<string, byte[]> after = Snapshot(f.Estate.Root);
        Assert.Equal(before.Keys.Append(migration.ExpectedPath).Order(StringComparer.Ordinal), after.Keys.Order(StringComparer.Ordinal));
        HashSet<string> rewritten = [.. members.Select(m => m.Path), EstateLayout.ManifestPath];
        Assert.All(before.Where(p => !rewritten.Contains(p.Key)), p => Assert.Equal(p.Value, after[p.Key]));
        Assert.NotEqual(before[EstateLayout.ManifestPath], after[EstateLayout.ManifestPath]);

        // The migration record says what was rewritten, register by register.
        string[] changes = [.. migration.Body.GetProperty("changes").EnumerateArray().Select(c => c.GetString()!)];
        foreach (var register in Registers)
        {
            string current = DocumentGenerators.Find(register.Generator)!.Descriptor!.Implementation;
            Assert.Contains($"docs/registers/{register.Directory}: 2 generated members rewritten by {current}; each held exactly the bytes {register.Earlier} wrote for the same sources", changes);
        }

        // New sources are accepted again, and their members are generated as before.
        Assert.True(service.NewRecord(new("work-order", f.Estate.OperatorId, PolicyFixture.Element(WorkOrder("TASK-LATER")))).Ok);
        Assert.DoesNotContain(EstateChecks.Run(service.Session.Load()), x => x.Code.StartsWith("document.", StringComparison.Ordinal));

        // Reapplying the installed target changes nothing and rewrites nothing.
        (UpgradeResponse? repeated, Problem? repeatProblem) = service.Upgrade(new UpgradeRequest(Target, f.Estate.OperatorId, false));
        Assert.Null(repeatProblem);
        Assert.False(repeated!.Applied);
        Assert.Empty(repeated.Regenerated);
    }

    [Fact]
    public void AMemberEditedByHandIsNeverRewrittenAndStaysGeneratedEdited()
    {
        using var f = new PolicyFixture();
        using EstateService service = Prepare(f);
        IReadOnlyList<Member> members = Members(service.Session.Load());
        foreach (Member member in members) File.WriteAllBytes(Full(f, member.Path), member.Earlier);
        // An earlier generator's bytes edited elsewhere, and a current generator's bytes edited: neither difference is the generator's.
        Member editedEarlier = members.First(m => m.Path.StartsWith("docs/registers/work/", StringComparison.Ordinal));
        Member editedCurrent = members.First(m => m.Path.StartsWith("docs/registers/releases/", StringComparison.Ordinal));
        File.WriteAllBytes(Full(f, editedEarlier.Path), Edit(editedEarlier.Earlier));
        File.WriteAllBytes(Full(f, editedCurrent.Path), Edit(editedCurrent.Current));
        string[] generatedOnly = [.. members.Select(m => m.Path).Where(p => p != editedEarlier.Path && p != editedCurrent.Path).Order(StringComparer.Ordinal)];
        Assert.Equal(2, generatedOnly.Length);

        (UpgradeResponse? preview, Problem? previewProblem) = service.Upgrade(new UpgradeRequest(Target, null, true));
        Assert.Null(previewProblem);
        Assert.Equal(generatedOnly, preview!.Regenerated);

        (UpgradeResponse? applied, Problem? problem) = service.Upgrade(new UpgradeRequest(Target, f.Estate.OperatorId, false));
        Assert.True(problem is null, JsonSerializer.Serialize(problem));
        Assert.True(applied!.Applied);
        Assert.Equal(generatedOnly, applied.Regenerated);
        Assert.Equal(Edit(editedEarlier.Earlier), File.ReadAllBytes(Full(f, editedEarlier.Path)));
        Assert.Equal(Edit(editedCurrent.Current), File.ReadAllBytes(Full(f, editedCurrent.Path)));
        Assert.All(members.Where(m => generatedOnly.Contains(m.Path)), m => Assert.Equal(m.Current, File.ReadAllBytes(Full(f, m.Path))));
        Assert.Equal(new[] { editedCurrent.Path, editedEarlier.Path }.Select(p => "Generated bytes differ: " + p).Order(StringComparer.Ordinal),
            EstateChecks.Run(service.Session.Load()).Where(x => x.Code == "document.generated-edited").Select(x => x.Message).Order(StringComparer.Ordinal));
        string[] changes = [.. Assert.Single(service.Session.Load().OfType("migration")).Body.GetProperty("changes").EnumerateArray().Select(c => c.GetString()!)];
        Assert.Contains(changes, c => c.StartsWith("docs/registers/work: 1 generated member rewritten by ", StringComparison.Ordinal));
        Assert.Contains(changes, c => c.StartsWith("docs/registers/releases: 1 generated member rewritten by ", StringComparison.Ordinal));
    }

    [Fact]
    public void EarlierImplementationsReproduceExactlyTheBytesTheirReleasesWrote()
    {
        string root = RepositoryRoot();
        EstateModel model = EstateLoader.Load(Path.Combine(root, "tests", "fixtures", "format-3-policy-estate"));
        Assert.False(model.Findings.HasErrors, string.Join('\n', model.Findings));
        foreach (string id in new[] { "vericairn.records/decisions", "vericairn.records/work-orders", "vericairn.records/releases" })
        {
            IDocumentGenerator generator = DocumentGenerators.Find(id)!;
            DocumentGeneratorDescriptor descriptor = generator.Descriptor!;
            IDocumentGenerator earlier = Assert.Single(generator.EarlierImplementations);
            DocumentGeneratorDescriptor earlierDescriptor = earlier.Descriptor!;
            Assert.Equal(id, earlier.Id);
            Assert.Equal(descriptor.ContractVersion, earlierDescriptor.ContractVersion);
            Assert.NotEqual(descriptor.Implementation, earlierDescriptor.Implementation);
            Assert.Equal(ContentHash.Sha256(Encoding.UTF8.GetBytes(earlierDescriptor.Implementation)), earlierDescriptor.ImplementationHash);
            Assert.Empty(earlier.EarlierImplementations);

            // The retained golden bytes are what that implementation wrote while it was current.
            string fixtures = Path.Combine(root, "tests", "fixtures", "readable-companions", earlierDescriptor.Implementation, "revisions");
            DocumentMemberSelection members = DocumentGeneration.Members(Declaration(id), DocumentSourceSelection.Records(model, descriptor));
            Assert.Equal(DocumentGenerationStatus.Success, members.Status);
            Assert.Equal(Directory.EnumerateFiles(fixtures, "*.md").Select(p => Path.GetFileName(p)).Order(StringComparer.Ordinal),
                members.Members.Select(m => Path.GetFileName(m.Path)).Order(StringComparer.Ordinal));
            foreach (DocumentMember member in members.Members)
            {
                DocumentRendition rendition = DocumentRendering.Render(earlier, member.Context with { Generator = earlierDescriptor });
                Assert.Equal(DocumentGenerationStatus.Success, rendition.Status);
                Assert.True(File.ReadAllBytes(Path.Combine(fixtures, Path.GetFileName(member.Path))).AsSpan().SequenceEqual(rendition.Bytes.AsSpan()),
                    "The earlier rendition differs from the retained bytes of " + earlierDescriptor.Implementation + ": " + Path.GetFileName(member.Path));
                Assert.False(DocumentRendering.Render(generator, member.Context).Bytes.AsSpan().SequenceEqual(rendition.Bytes.AsSpan()));
            }
        }

        // A revision that records a field the earlier implementation never rendered has no earlier rendition to match.
        IDocumentGenerator work = DocumentGenerators.Find("vericairn.records/work-orders")!;
        RecordEnvelope original = model.OfType("work-order").First(r => r.Supersedes is null);
        JsonObject body = PolicyFixture.Body(original);
        body["disclosure"] = "held";
        RecordEnvelope held = RecordAuthor.Create(new RecordDraft("work-order", original.By, PolicyFixture.Element(body), original.Subject,
            At: original.AtTime, Id: original.Id, Format: 3)).Envelope;
        DocumentMember heldMember = Assert.Single(DocumentGeneration.Members(Declaration(work.Id),
            new(DocumentGenerationStatus.Success, [DocumentSourceSnapshot.Record(held)], null, null)).Members);
        Assert.Equal(DocumentGenerationStatus.Success, DocumentRendering.Render(work, heldMember.Context).Status);
        IDocumentGenerator prior = Assert.Single(work.EarlierImplementations);
        Assert.Equal(DocumentGenerationStatus.Unavailable, DocumentRendering.Render(prior, heldMember.Context with { Generator = prior.Descriptor! }).Status);
    }

    private sealed record Member(string Path, byte[] Current, byte[] Earlier);

    /// <summary>
    /// Two work-order revisions and two release revisions, the release being the upgrade's target, and both registers declared through the
    /// runtime with an admitted signing device, so every member holds the current generator's bytes.
    /// </summary>
    private static EstateService Prepare(PolicyFixture f)
    {
        RecordEnvelope order = f.Add("work-order", WorkOrder("TASK-0"));
        JsonObject revised = PolicyFixture.Body(order);
        revised["intent"] = "Perform the declared checks, revised.";
        f.Add("work-order", revised, supersedes: order.Id);
        Publish(f, Target);
        f.AssertValid();
        EstateService service = EstateService.Open(f.Estate.Root);
        RecordWritten device = Ok(service.DeviceCreate(new(f.Estate.OperatorId, "Register writer", "file")));
        // Admitted at the device's own second, so the runtime's later writes, the migration among them, are signed after the admission.
        f.Estate.SetClock(service.Session.Load().ById[device.Id].AtTime.AddSeconds(-1));
        f.Add("admission", new JsonObject { ["principal"] = f.Estate.OperatorId, ["status"] = "admitted", ["note"] = "Register writer." },
            subject: service.Session.Load().ById[device.Id].Reference);
        foreach (var register in Registers)
        {
            JsonObject body = CompanionReadTests.Declaration();
            body["pathPattern"] = "docs/registers/" + register.Directory + "/{month}/{date}-{slug}-{id}.md";
            body["generator"]!["id"] = register.Generator;
            body["title"] = "Recorded " + register.Directory;
            Ok(service.NewRecord(new("living-document", f.Estate.OperatorId, PolicyFixture.Element(body))));
        }

        Assert.DoesNotContain(EstateChecks.Run(service.Session.Load()), x => x.Code.StartsWith("document.", StringComparison.Ordinal));
        return service;
    }

    /// <summary>
    /// Every register member with the current generator's bytes and the bytes 0.8.4 wrote for it: the current rendition without the
    /// sections of the fields added since, and the input digest the earlier implementation identity gives the same sources.
    /// </summary>
    private static List<Member> Members(EstateModel model)
    {
        var members = new List<Member>();
        foreach (var register in Registers)
        {
            IDocumentGenerator generator = DocumentGenerators.Find(register.Generator)!;
            DocumentGeneratorDescriptor descriptor = generator.Descriptor!;
            RecordEnvelope declaration = model.Current("living-document").Single(d => d.Body.GetProperty("generator").GetProperty("id").GetString() == register.Generator);
            DocumentMemberSelection selection = DocumentGeneration.Members(declaration, DocumentSourceSelection.Records(model, descriptor));
            Assert.Equal(DocumentGenerationStatus.Success, selection.Status);
            Assert.Equal(2, selection.Members.Length);
            foreach (DocumentMember member in selection.Members)
            {
                DocumentRendition current = DocumentRendering.Render(generator, member.Context);
                Assert.Equal(DocumentGenerationStatus.Success, current.Status);
                string text = Encoding.UTF8.GetString(current.Bytes.AsSpan());
                string earlierDigest = (member.Context with
                {
                    Generator = descriptor with { Implementation = register.Earlier, ImplementationHash = ContentHash.Sha256(Encoding.UTF8.GetBytes(register.Earlier)) },
                }).InputDigest;
                string digestLine = "Input digest: " + member.Context.InputDigest + ".";
                Assert.Equal(2, text.Split(digestLine).Length);
                text = text.Replace(digestLine, "Input digest: " + earlierDigest + ".", StringComparison.Ordinal);
                FieldDescription[] fields = [.. RecordTypeRegistry.Find(register.Type)!.Fields];
                foreach ((string field, string label) in register.Added)
                {
                    string section = "\n\n## " + label + "\n\n" + DocumentMarkdown.Text(fields.Single(x => x.Name == field).Description) + "\n\n" + NotRecorded;
                    Assert.Contains(section, text, StringComparison.Ordinal);
                    text = text.Replace(section, string.Empty, StringComparison.Ordinal);
                }

                members.Add(new(member.Path, current.Bytes.ToArray(), Encoding.UTF8.GetBytes(text)));
            }
        }

        return members;
    }

    private static byte[] Edit(byte[] bytes)
    {
        string text = Encoding.UTF8.GetString(bytes);
        Assert.Contains("Recorded revision; Internal.", text, StringComparison.Ordinal);
        return Encoding.UTF8.GetBytes(text.Replace("Recorded revision; Internal.", "Recorded revision; Internal; annotated by hand.", StringComparison.Ordinal));
    }

    private static JsonObject WorkOrder(string key) => new()
    {
        ["key"] = key, ["kind"] = "ordinary", ["title"] = "Maintenance " + key, ["intent"] = "Perform the declared checks.", ["scope"] = new JsonArray("test inventory"),
        ["exitQuestion"] = "Was the inventory checked?", ["inputs"] = new JsonArray(), ["deliverables"] = new JsonArray("report"),
    };

    private static void Publish(PolicyFixture f, string version)
    {
        RecordEnvelope product = f.Add("product", new JsonObject
        {
            ["name"] = "Example", ["slug"] = "example", ["summary"] = "Test upgrade product.",
            ["editions"] = new JsonArray(new JsonObject { ["name"] = "Community", ["slug"] = "community", ["summary"] = "Test edition." }),
            ["surfaces"] = new JsonArray(new JsonObject { ["name"] = "CLI", ["slug"] = "cli", ["summary"] = "Test surface." }),
        });
        JsonObject body = new()
        {
            ["version"] = version, ["repository"] = "Example/example", ["commit"] = new string('1', 40), ["status"] = "candidate",
            ["artifacts"] = new JsonArray(new JsonObject { ["name"] = EstateUpgrade.DistributableName(version, "linux-x64"), ["hash"] = "sha256:" + new string('1', 64), ["bytes"] = 10, ["platform"] = "linux-x64" }),
            ["recordFormat"] = new JsonObject { ["reads"] = new JsonArray(1, 2, 3), ["writes"] = 3 }, ["evidence"] = new JsonArray(), ["qualified"] = new JsonArray(),
            ["signing"] = "unsigned test artifact", ["limitations"] = new JsonArray(),
        };
        RecordEnvelope candidate = f.Add("release", body, subject: new RecordReference("product", product.Id, null));
        f.Add("acceptance", new JsonObject { ["statement"] = "Test release accepted.", ["basis"] = new JsonArray(), ["self"] = true }, subject: candidate.Reference);
        body["status"] = "published";
        body["publishedAt"] = RecordParser.FormatTimestamp(f.Estate.Clock);
        body["url"] = "https://example.invalid/releases/" + version;
        f.Add("release", body, subject: candidate.Subject, supersedes: candidate.Id);
    }

    private static RecordEnvelope Declaration(string id) => RecordAuthor.Create(new RecordDraft("living-document", "01ARZ3NDEKTSV4RRFFQ69G5FAV", PolicyFixture.Element(new JsonObject
    {
        ["pathPattern"] = DocumentGenerators.Find(id)!.Descriptor!.RequiredPattern, ["title"] = "Recorded revisions", ["kind"] = "generated", ["source"] = "estate-file",
        ["generator"] = new JsonObject { ["id"] = id, ["inputs"] = new JsonArray("format=1", "audience=Internal", "selection=all-revisions") },
        ["triggers"] = new JsonArray(), ["checks"] = new JsonArray("matches-generator", "links-resolve"), ["summary"] = "One file per exact revision.",
    }), Format: 3)).Envelope;

    private static string Full(PolicyFixture f, string path) => Path.Combine(f.Estate.Root, path.Replace('/', Path.DirectorySeparatorChar));

    // Repository content only; the runtime's machine-local state is not part of what an upgrade may change.
    private static Dictionary<string, byte[]> Snapshot(string root) => Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
        .Select(p => Path.GetRelativePath(root, p).Replace('\\', '/')).Where(p => !p.StartsWith(".vericairn/", StringComparison.Ordinal))
        .ToDictionary(p => p, p => File.ReadAllBytes(Path.Combine(root, p)), StringComparer.Ordinal);

    private static void AssertSnapshot(Dictionary<string, byte[]> expected, Dictionary<string, byte[]> actual)
    {
        Assert.Equal(expected.Keys.Order(StringComparer.Ordinal), actual.Keys.Order(StringComparer.Ordinal));
        Assert.All(expected, p => Assert.Equal(p.Value, actual[p.Key]));
    }

    private static RecordWritten Ok(WriteOutcome outcome)
    {
        Assert.True(outcome.Ok, JsonSerializer.Serialize(outcome.Problem));
        return outcome.Written!;
    }

    private static string RepositoryRoot()
    {
        string? root = AppContext.BaseDirectory;
        while (root is not null && !File.Exists(Path.Combine(root, "Vericairn.slnx"))) root = Path.GetDirectoryName(root);
        Assert.NotNull(root);
        return root;
    }
