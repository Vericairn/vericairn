    [Fact]
    public async Task RefreshRetainsTheExactRevisionAndClearsEveryCachedViewWhenAccessIsLost()
    {
        string root = Seed.Temp("companion-view");
        string person = Seed.Init(root);
        using EstateService service = EstateService.Open(root);
        WriteOutcome written = service.NewRecord(new("decision", person, Decision(person)));
        Assert.True(written.Ok, written.Problem?.Message);
        string id = written.Written!.Id;
        var page = new CompanionDocument(new("vericairn.records/items", "item", id));
        await fixture.UiAsync(() => page.RefreshAsync(service, cancellationToken: TestContext.Current.CancellationToken));
        string original = page.Text;
        Assert.Equal("current", page.Currentness);
        Assert.Contains(id, page.SourceText, StringComparison.Ordinal);
        Assert.Contains(written.Written.Hash, Assert.Single(page.Sources).AccessibleName, StringComparison.Ordinal);

        JsonObject revised = JsonNode.Parse(Decision(person).GetRawText())!.AsObject();
        revised["summary"] = "A revised explanation; the recorded words remain exact.";
        WriteOutcome successor = service.NewRecord(new("decision", person, Seed.Json(revised.ToJsonString()), Supersedes: id));
        Assert.True(successor.Ok, successor.Problem?.Message);
        await fixture.UiAsync(() => page.RefreshAsync(service, cancellationToken: TestContext.Current.CancellationToken));
        Assert.Equal(id, page.Request.Revision);
        Assert.Equal("historical", page.Currentness);
        Assert.Equal(original, page.Text);
        Assert.Contains("Generated bytes are unchanged", page.Difference, StringComparison.Ordinal);
        Assert.Contains("Earlier observation", page.PreviousText, StringComparison.Ordinal);
        Assert.DoesNotContain(successor.Written!.Id, page.SourceText, StringComparison.Ordinal);
        Assert.Contains("clears no authored review", page.EditGuidance, StringComparison.Ordinal);

        using (service.ForDeviceRequest("unavailable-device", "unavailable-key"))
        {
            await fixture.UiAsync(() => page.RefreshAsync(service, cancellationToken: TestContext.Current.CancellationToken));
        }
        Assert.Equal("unavailable", page.Currentness);
        Assert.Empty(page.Text);
        Assert.Empty(page.SourceText);
        Assert.Empty(page.PreviousText);
        Assert.Empty(page.Sources);
        Assert.DoesNotContain(written.Written.Hash, page.Basis, StringComparison.Ordinal);
    }

    [Fact]
    [Trait("Journey", "D19-F")]
    public async Task AMissingReaderRetainsTheAuthorizedExactSourceInspector()
    {
        string root = Seed.Temp("companion-unavailable-reader");
        string person = Seed.Init(root);
        using EstateService service = EstateService.Open(root);
        var page = new CompanionDocument(new("example.journeys/removed", "item", person));
        await fixture.UiAsync(() => page.RefreshAsync(service, cancellationToken: TestContext.Current.CancellationToken));
        Assert.Equal("unavailable", page.Currentness);
        Assert.Empty(page.Text);
        Assert.Contains(person, page.SourceText, StringComparison.Ordinal);
        Assert.Equal(service.Record(person)!.Hash, Assert.Single(page.Sources).Source.Hash);
        Assert.Contains("rendition remains unavailable", page.Basis, StringComparison.Ordinal);
        using (service.ForDeviceRequest("unavailable-device", "unavailable-key"))
            await fixture.UiAsync(() => page.RefreshAsync(service, cancellationToken: TestContext.Current.CancellationToken));
        Assert.Empty(page.SourceText);
        Assert.Empty(page.Sources);
    }

    [Fact]
    public async Task KeyboardCollectionAndSourceNavigationExposeExactAccessibleBasisWithoutWriting()
    {
        string root = Seed.Temp("companion-keyboard");
        string person = Seed.Init(root);
        var shell = new ShellViewModel(r => new ServiceConnection(r), new FakeRuntimeManager(), new Preferences(Seed.Temp("companion-preferences"))) { ActingOverride = person };
        MainWindow window = await fixture.Ui(() => { var w = new MainWindow(shell); w.Show(); return w; });
        try
        {
            await fixture.UiAsync(() => shell.OpenEstateAsync(root, cancellationToken: TestContext.Current.CancellationToken));
            WriteOutcome decision = shell.Api!.NewRecord(new("decision", person, Decision(person)));
            Assert.True(decision.Ok, decision.Problem?.Message);
            int before = Directory.EnumerateFiles(Path.Combine(root, "records"), "*.json", SearchOption.AllDirectories).Count();
            await fixture.UiAsync(async () =>
            {
                window.Focus();
                window.KeyPress(Key.V, RawInputModifiers.Control | RawInputModifiers.Shift, PhysicalKey.V, null);
                await shell.PendingOperation;
            });
            CompanionCatalogDocument catalog = Assert.IsType<CompanionCatalogDocument>(shell.SelectedDocument);
            Assert.Equal(6, catalog.Rows.Count(r => r.Pattern is not null));
            Assert.DoesNotContain(catalog.Rows, r => r.LocalOnly);
            // Focus, selection and Enter share one dispatch, as a person's keystrokes would: between dispatches the headless
            // window can lose its focused element.
            await fixture.UiAsync(async () =>
            {
                Keys.Focus(window, "Readable collections");
                ListBox list = window.GetVisualDescendants().OfType<ListBox>().Single(l => AutomationProperties.GetName(l) == "Readable collections");
                list.SelectedItem = catalog.Rows.Single(r => r.Id == "vericairn.records/decisions");
                window.KeyPress(Key.Enter, RawInputModifiers.None, PhysicalKey.Enter, null);
                await shell.PendingOperation;
            });
            CompanionDocument collection = Assert.IsType<CompanionDocument>(shell.SelectedDocument);
            Assert.Equal(catalog.Coverage.Snapshot, collection.Request.Snapshot);
            Assert.Contains(decision.Written!.Id, Assert.Single(collection.Sources).AccessibleName, StringComparison.Ordinal);
            await fixture.UiAsync(async () =>
            {
                Keys.Focus(window, "Companion source identities hashes and currentness");
                window.KeyPress(Key.Enter, RawInputModifiers.None, PhysicalKey.Enter, null);
                await shell.PendingOperation;
            });
            CompanionDocument item = Assert.IsType<CompanionDocument>(shell.SelectedDocument);
            Assert.Equal(decision.Written.Id, item.Request.Revision);
            Assert.Contains(decision.Written.Id, item.SourceText, StringComparison.Ordinal);
            await fixture.Ui(() =>
            {
                Keys.Focus(window, "Companion revision basis and currentness");
                Keys.Focus(window, "Complete readable companion");
                TextBox text = window.GetVisualDescendants().OfType<TextBox>().Single(t => AutomationProperties.GetName(t) == "Complete readable companion" && t.IsEffectivelyVisible);
                Assert.True(text.IsReadOnly);
                Keys.Focus(window, "Exact source envelope or file basis");
            });
            Assert.Equal(before, Directory.EnumerateFiles(Path.Combine(root, "records"), "*.json", SearchOption.AllDirectories).Count());
        }
        finally { await fixture.Ui(window.Close); }
    }

    private static System.Text.Json.JsonElement Decision(string person) => Seed.Json($$"""
        {"title":"A readable decision","stake":"low","notAuthorized":[],"statement":"Keep the source exact.",
         "summary":"Read alongside the source.","synthesis":"The source controls the view.","effects":["Readable view"],
         "affects":[],"decidedBy":"{{person}}","decidedAt":"2026-10-13T12:00:00Z"}
        """);
}
