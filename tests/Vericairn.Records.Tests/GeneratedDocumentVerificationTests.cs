    [Fact]
    public void NewDeclarationsRequireEveryMemberAndExactBytesWithoutAnOutputPin()
    {
        using var f = new PolicyFixture();
        RecordEnvelope declaration = f.Add("living-document", DocumentGenerationTests.Declaration());
        GeneratedDocumentPlan missing = GeneratedDocumentVerification.Plan(f.Estate.Load(), declaration);
        Assert.False(missing.Current);
        string path = Assert.Single(missing.Expected).Path;
        Assert.Contains(missing.Problems, p => p.Contains("Missing", StringComparison.Ordinal));
        f.Estate.WriteFile(path, "Approve the stated definition only.\n");
        Assert.True(GeneratedDocumentVerification.Plan(f.Estate.Load(), declaration).Current);
        Assert.Empty(f.Estate.Load().OfType("document-revision"));
        Assert.DoesNotContain(EstateChecks.Run(f.Estate.Load()), p => p.Code.StartsWith("document.generated", StringComparison.Ordinal));

        f.Estate.WriteFile(path, "Approve the stated definition only.\r\n");
        Assert.Contains(EstateChecks.Run(f.Estate.Load()), p => p.Code == "document.generated-edited");
        f.Estate.WriteFile("docs/registers/decisions/orphan.md", "An extra file.\n");
        Assert.Contains(GeneratedDocumentVerification.Plan(f.Estate.Load(), declaration).Problems, p => p.Contains("Unexpected", StringComparison.Ordinal));
    }

    [Fact]
    public void AFormatUpgradeAndAnEditorialSuccessorKeepLegacyPinsUntilReviewedMigration()
    {
        using var f = new PolicyFixture(2);
        JsonObject legacyBody = DocumentGenerationTests.Declaration(null);
        legacyBody["generator"]!["inputs"] = new JsonArray();
        legacyBody["triggers"] = new JsonArray(new JsonObject { ["on"] = "decision", ["level"] = "warn" });
        RecordEnvelope legacy = f.Add("living-document", legacyBody);
        f.Estate.WriteFile("docs/decisions.md", "Old generated bytes.\n");
        RecordEnvelope pin = Pin(f, "docs/decisions.md", "Old generated bytes.\n");
        byte[] oldPin = File.ReadAllBytes(Path.Combine(f.Estate.Root, pin.ExpectedPath));
        f.Estate.MoveTo(3);
        legacyBody["title"] = "An edited title";
        RecordEnvelope editorial = f.Add("living-document", legacyBody, supersedes: legacy.Id);
        Assert.False(GeneratedDocumentContract.IsStrict(f.Estate.Load(), editorial));
        f.Estate.WriteFile("docs/decisions.md", "Hand edit.\n");
        Assert.Contains(EstateChecks.Run(f.Estate.Load()), p => p.Code == "document.drift");

        JsonObject next = DocumentGenerationTests.Declaration(null);
        AuthoredRecord proposal = RecordAuthor.Create(new RecordDraft("living-document", f.Estate.OperatorId, PolicyFixture.Element(next), Supersedes: editorial.Id, At: f.Estate.Clock.AddMinutes(1), Format: 3), [f.OperatorSigner]);
        DocumentMigrationPreview preview = DocumentMigration.Prepare(f.Estate.Load(), proposal.Envelope);
        Assert.Equal(DocumentGenerationStatus.Success, preview.Status);
        Assert.Contains(pin.Id, Encoding.UTF8.GetString(preview.Preview.AsSpan()), StringComparison.Ordinal);
        Assert.Single(preview.Before);
        Assert.Single(preview.After);
        RecordEnvelope result = f.Result();
        JsonObject resultBody = PolicyFixture.Body(result);
        resultBody["outputs"] = new JsonArray(
            new JsonObject { ["name"] = GeneratedDocumentContract.MigrationOutput, ["hash"] = preview.BasisHash },
            new JsonObject { ["name"] = GeneratedDocumentContract.MigrationPreviewOutput, ["hash"] = preview.PreviewHash });
        resultBody["evidence"] = new JsonArray(preview.Pins.Select(p => (JsonNode)new JsonObject
        {
            ["summary"] = "Historical pin retained by this migration.", ["hash"] = p.Hash, ["location"] = f.Estate.Load().ById[p.Id].ExpectedPath,
        }).ToArray());
        RecordEnvelope submitted = f.Add("result", resultBody, builder: true, subject: result.Subject, supersedes: result.Id);
        f.Review(submitted);
        AuthoredRecord prepared = RecordAuthor.Create(new RecordDraft("living-document", f.Estate.OperatorId, PolicyFixture.Element(next), Supersedes: editorial.Id,
            At: f.Estate.Clock.AddMinutes(1), Format: 3), [f.OperatorSigner]);
        EstateModel before = f.Estate.Load();
        EstateModel proposed = With(f, prepared);
        Assert.Equal(DocumentGenerationStatus.Success, DocumentRecordChanges.Prepare(before, proposed, [prepared.Envelope]).Status);
        f.Estate.WriteFile("docs/decisions.md", "Changed after the preview was reviewed.\n");
        DocumentChangePlan stale = DocumentRecordChanges.Prepare(f.Estate.Load(), With(f, prepared), [prepared.Envelope]);
        Assert.Equal(DocumentGenerationStatus.Error, stale.Status);
        Assert.Empty(stale.Changes);
        Assert.False(File.Exists(Path.Combine(f.Estate.Root, prepared.RelativePath)));
        f.Estate.WriteFile("docs/decisions.md", "Hand edit.\n");
        RecordEnvelope adopted = f.Add("living-document", next, supersedes: editorial.Id);
        f.AssertValid();
        Assert.True(GeneratedDocumentContract.IsStrict(f.Estate.Load(), adopted));
        f.Estate.WriteFile("docs/decisions.md", "Approve the stated definition only.\n");
        Assert.DoesNotContain(EstateChecks.Run(f.Estate.Load()), p => p.Code == "document.drift");
        Assert.Equal(oldPin, File.ReadAllBytes(Path.Combine(f.Estate.Root, pin.ExpectedPath)));
        Assert.Single(f.Estate.Load().OfType("document-revision"));
    }

    [Fact]
    public void RestoringAuthoredOwnershipNeedsItsExactPinInThePreparedBatch()
    {
        using var f = new PolicyFixture();
        RecordEnvelope generated = f.Add("living-document", DocumentGenerationTests.Declaration(null));
        const string content = "Approve the stated definition only.\n";
        f.Estate.WriteFile("docs/decisions.md", content);
        JsonObject authored = PolicyFixture.Body(generated);
        authored["kind"] = "authored";
        authored.Remove("generator");
        authored["triggers"] = new JsonArray(new JsonObject { ["on"] = "decision", ["level"] = "warn" });
        AuthoredRecord proposal = RecordAuthor.Create(new RecordDraft("living-document", f.Estate.OperatorId, PolicyFixture.Element(authored),
            Supersedes: generated.Id, At: f.Estate.Clock.AddMinutes(1), Format: 3), [f.OperatorSigner]);
        DocumentMigrationPreview preview = DocumentMigration.Prepare(f.Estate.Load(), proposal.Envelope);
        Assert.Equal(DocumentGenerationStatus.Success, preview.Status);
        ReviewMigration(f, preview);
        AuthoredRecord successor = RecordAuthor.Create(new RecordDraft("living-document", f.Estate.OperatorId, PolicyFixture.Element(authored),
            Supersedes: generated.Id, At: f.Estate.Clock.AddMinutes(1), Format: 3), [f.OperatorSigner]);
        Assert.Equal(DocumentGenerationStatus.Error, DocumentRecordChanges.Prepare(f.Estate.Load(), With(f, successor), [successor.Envelope]).Status);
        var pinBody = new JsonObject { ["path"] = "docs/decisions.md", ["title"] = "Restored authored document", ["hash"] = ContentHash.Sha256(Encoding.UTF8.GetBytes(content)),
            ["bytes"] = Encoding.UTF8.GetByteCount(content), ["mediaType"] = "text/markdown", ["revision"] = 1, ["summary"] = "Restore exact authored custody." };
        AuthoredRecord pin = RecordAuthor.Create(new RecordDraft("document-revision", f.Estate.OperatorId, PolicyFixture.Element(pinBody), At: f.Estate.Clock.AddMinutes(1), Format: 3), [f.OperatorSigner]);
        EstateModel proposed = With(f, successor, pin);
        Assert.False(proposed.Findings.HasErrors, string.Join('\n', proposed.Findings));
        Assert.Equal(DocumentGenerationStatus.Success, DocumentRecordChanges.Prepare(f.Estate.Load(), proposed, [successor.Envelope, pin.Envelope]).Status);
        Assert.Empty(f.Estate.Load().OfType("document-revision"));
    }

    [Fact]
    public void AuthoredRegionContractChangesRequireAnExplicitReviewedMigration()
    {
        using var f = new PolicyFixture();
        var body = new JsonObject { ["path"] = "docs/guide.md", ["title"] = "Guide", ["kind"] = "authored", ["source"] = "estate-file",
            ["triggers"] = new JsonArray(new JsonObject { ["on"] = "decision", ["level"] = "warn" }),
            ["regions"] = new JsonArray(new JsonObject { ["id"] = "releases", ["generator"] = "vericairn.records/releases" }), ["summary"] = "Keep authored guidance." };
        RecordEnvelope old = f.Add("living-document", body);
        body["regions"]![0]!["generator"] = "example.documents/unavailable";
        RecordEnvelope changed = f.Add("living-document", body, supersedes: old.Id);
        Assert.Contains(f.Estate.Load().Findings, p => p.Code == "document.migration" && p.Location == changed.ExpectedPath);
    }

    [Fact]
    public void UnreviewedLegacyConversionAndAuthoredPinBypassAreRefused()
    {
        using var f = new PolicyFixture(2);
        JsonObject legacy = DocumentGenerationTests.Declaration(null);
        legacy["generator"]!["inputs"] = new JsonArray();
        legacy["triggers"] = new JsonArray(new JsonObject { ["on"] = "decision", ["level"] = "warn" });
        RecordEnvelope previous = f.Add("living-document", legacy);
        f.Estate.MoveTo(3);
        RecordEnvelope successor = f.Add("living-document", DocumentGenerationTests.Declaration(null), supersedes: previous.Id);
        Assert.Contains(f.Estate.Load().Findings, p => p.Code == "document.migration" && p.Location.StartsWith(successor.ExpectedPath, StringComparison.Ordinal));
        Assert.False(GeneratedDocumentContract.IsStrict(f.Estate.Load(), successor));

        using var authored = new PolicyFixture();
        Pin(authored, "docs/decisions.md", "Authored words.\n");
        authored.Add("living-document", DocumentGenerationTests.Declaration(null));
        Assert.Contains(authored.Estate.Load().Findings, p => p.Code == "document.migration");
    }

    [Fact]
    public void MissingGeneratorNeverFallsBackToPinsAndAuthoredDriftStillFails()
    {
        using var f = new PolicyFixture();
        Pin(f, "docs/authored.md", "Original authored prose.\n");
        f.Estate.WriteFile("docs/authored.md", "Changed authored prose.\n");
        JsonObject body = DocumentGenerationTests.Declaration(null);
        body["generator"]!["id"] = "example.documents/absent";
        RecordEnvelope declaration = f.Add("living-document", body);
        Assert.Equal(DocumentGenerationStatus.Unavailable, GeneratedDocumentVerification.Plan(f.Estate.Load(), declaration).Status);
        FindingList checks = EstateChecks.Run(f.Estate.Load());
        Assert.Contains(checks, p => p.Code == "document.generated-unavailable");
        Assert.Contains(checks, p => p.Code == "document.drift");
    }

