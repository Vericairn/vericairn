using System.CommandLine;

namespace Vericairn.Cli;

internal sealed class DocsCommand : Command
{
    public DocsCommand(CommandContext context)
        : base("docs", "Documentation: a release's set (its notes from the estate's records, and the check that a set holds every document its manifest lists; the references are generated by the product's own build tooling), and the living documents that stay true as the estate changes.")
    {
        Subcommands.Add(new DocsNotesCommand(context));
        Subcommands.Add(new DocsCheckCommand(context));
        Subcommands.Add(new DocsLivingCommand(context));
        Subcommands.Add(new DocsReviewCommand(context));
        Subcommands.Add(new DocsDeclareCommand(context));
        Subcommands.Add(new DocsRegenerateCommand(context));
    }
}
